HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CONFIG = ROOT / "configs/visual_sprites_lejepa/default.json"
RESULTS = ROOT / "results/visual_sprites_lejepa"
METRICS = ROOT / "src/slowrepr/metrics.py"
SIGREG = ROOT / "work/hcf_stable_id_20261027/v1/vendor/lejepa_identifiability/experiments/lejepa_id/losses.py"
ARMS = ("visual_lejepa", "long_horizon_pred")
AXES = ("agent_x", "agent_y", "distractor_x", "distractor_y")


def utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="microseconds")


def sha256(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def save_json(path, value):
    with path.open("x") as stream:
        json.dump(value, stream, indent=2, allow_nan=False, ensure_ascii=False)
        stream.write("\n")


def read_json(path):
    return json.loads(path.read_text())


def source_hashes():
    return {str(path.relative_to(ROOT)): sha256(path) for path in sorted(
        [CONFIG, METRICS, SIGREG, *HERE.glob("*.py")])}


def result_path(name):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", name):
        raise ValueError("Result names must use only letters, digits, underscores and hyphens")
    path = RESULTS / name
    if path.resolve() != path or RESULTS.resolve() != RESULTS:
        raise ValueError("Results must stay within the physical experiment directory")
    return path


def load_metrics():
    # Load the exact repository scorer without importing separate research packages.
    spec = importlib.util.spec_from_file_location("sealed_fourroom_metrics", METRICS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cells(cfg, development=False):
    seeds = [cfg["development_model_seed"]] if development else cfg["seeds"]
    arms = ARMS[:1] if development and not cfg.get("fixture_only") else ARMS
    return [(f"{arm}_seed{seed}", arm, seed) for arm in arms for seed in seeds]


def save_npz(path, **arrays):
    with path.open("xb") as stream:
        np.savez(stream, **arrays)


def save_model(path, value, torch):
    with path.open("xb") as stream:
        torch.save(value, stream)


def verify_locked_sources(lock):
    if lock["source_sha256"] != source_hashes():
        raise ValueError("Source/config hashes differ from the design lock")


def initialize_output(out, cfg, device, mode, preflight, development_receipt=None):
    out.mkdir(parents=True, exist_ok=False)
    lock = {
        "evidence_tier": "formal_visual_sprites" if mode == "formal" else mode,
        "mode": mode,
        "created_utc": utc_now(),
        "device": str(device),
        "config": cfg,
        "source_sha256": source_hashes(),
        "development_preflight": preflight,
        "development_receipt": development_receipt,
        "test_seal_protocol": (
            "A separate renderer transforms transient latent states into TEST image bytes. "
            "The inference process receives only those bytes. TEST physical labels are "
            "regenerated by the scoring stage only after prediction and threshold hashes "
            "have been sealed and verified. UTC timestamps are local process records."
        ),
        "scoring_targets": "Four Gaussian latent coordinates in canonical entity/axis order",
    }
    save_json(out / "DESIGN_LOCK.json", lock)
    return lock


def role_labels(cfg, role, development):
    truth = render.sample_states(cfg, role, development=development)
    return render.sample_frames(truth, cfg, role, development=development)


def fixture_panel(cfg):
    """Use an isolated development-only AUDIT stream as the tiny blind fixture."""
    fixture = deepcopy(cfg)
    fixture["development_seed"] += 1
    fixture["roles"]["audit"] = cfg["roles"]["test"]
    return fixture


def image_batch_size(cfg):
    return cfg["runtime"].get("render_batch_size", cfg["runtime"]["encode_batch_size"])


def render_pretrain(cfg, development, batch):
    spec = cfg["roles"]["pretrain"]
    episodes, frames = spec["episodes"], spec["frames"]
    shape = (episodes * frames, 3, 32, 32)
    images = np.empty(shape, dtype=np.float32)
    cursor = 0
    for group in render.iter_role_images(cfg, "pretrain", batch, development=development):
        images[cursor:cursor + len(group)] = group
        cursor += len(group)
    if cursor != shape[0]:
        raise ValueError(f"Rendered {cursor} PRETRAIN frames, expected {shape[0]}")
    return images.reshape(episodes, frames, *shape[1:])


def features_for_images(encoders, images, models, cfg, device):
    blocks = {name: [] for name in encoders}
    for frames in images:
        for name, encoder in encoders.items():
            blocks[name].append(models.encode(encoder, frames, device, cfg["runtime"]["encode_batch_size"]))
    return {name: np.concatenate(values) for name, values in blocks.items()}


def features_for_role(encoders, cfg, role, develop, models, device):
    source = render.iter_role_images(cfg, role, image_batch_size(cfg), development=develop)
    return features_for_images(encoders, source, models, cfg, device)


def prepare_models(out, cfg, models, torch, device, develop):
    started = time.perf_counter()
    pretrain = render_pretrain(cfg, develop, image_batch_size(cfg))
    encoders = {}
    for name, arm, seed in cells(cfg, develop):
        folder = out / name
        folder.mkdir()
        start = time.perf_counter()
        encoder, trace = models.train_encoder(pretrain, cfg, arm, seed, device)
        encoders[name] = encoder.eval()
        save_model(folder / "encoder.pt", encoder.state_dict(), torch)
        save_json(folder / "encoder_trace.json", {"arm": arm, "seed": seed, "trace": trace,
                                                "elapsed_seconds": time.perf_counter() - start})
        print(f"Pretraining complete: {name}", flush=True)
    del pretrain

    train = features_for_role(encoders, cfg, "train", develop, models, device)
    val = features_for_role(encoders, cfg, "val", develop, models, device)
    audit_features = features_for_role(encoders, cfg, "audit", develop, models, device)
    train_y, val_y, audit_y = [role_labels(cfg, role, develop).reshape(-1, 4)
                               for role in ("train", "val", "audit")]
    audit_variance = audit_y.var(0, ddof=0)
    if np.any(audit_variance <= 0):
        raise ValueError("A physical AUDIT factor has zero variance")
    probes, audit_rows = {}, {}
    for name, arm, seed in cells(cfg, develop):
        folder = out / name
        probe, trace = models.fit_probe(train[name], train_y, val[name], val_y, cfg, seed, device)
        probes[name] = probe
        save_model(folder / "probe.pt", probe, torch)
        save_json(folder / "probe.json", {"trace": trace, "seed": seed, "best_step": probe["best_step"],
                                           "validation_loss": probe["validation_loss"]})
        pred = models.predict(probe, audit_features[name], device)
        r2 = 1 - np.mean((pred - audit_y)**2, axis=0) / audit_variance
        audit_rows[name] = {"arm": arm, "seed": seed, "r2": dict(zip(AXES, r2.tolist())),
                            "minimum_r2": float(r2.min()),
                            "eligible": bool(np.min(r2) >= cfg["audit_min_r2"])}
        save_json(folder / "audit.json", audit_rows[name])
        save_npz(folder / "audit.npz", prediction=pred, truth=audit_y)
    print(f"AUDIT complete ({time.perf_counter() - started:.1f} s)", flush=True)
    return encoders, probes, audit_rows


def render_test_stream(out):
    """Internal render-only process. Its stdout contains only pixel bytes."""
    lock = read_json(out / "DESIGN_LOCK.json")
    if lock["mode"] not in ("formal", "development_smoke") or (out / "FORECAST_RECEIPT.json").exists():
        raise ValueError("The image renderer requires an active pre-forecast lock")
    verify_locked_sources(lock)
    cfg = lock["config"]
    fixture = lock["mode"] == "development_smoke"
    if fixture:
        cfg = fixture_panel(cfg)
    role = "audit" if fixture else "test"
    for images in render.iter_role_images(cfg, role, image_batch_size(cfg), development=fixture):
        sys.stdout.buffer.write(memoryview(np.ascontiguousarray(images)).cast("B"))


def blind_image_batches(out, cfg, image_record):
    spec = cfg["roles"]["test"]
    total_frames = spec["episodes"] * spec["frames"]
    image_shape = (3, 32, 32)
    batch = image_batch_size(cfg)
    digest = hashlib.sha256()
    command = [sys.executable, "-B", str(Path(__file__).resolve()), "--render-test", "--name", out.name]
    with subprocess.Popen(command, stdout=subprocess.PIPE) as renderer:
        try:
            for start in range(0, total_frames, batch):
                count = min(batch, total_frames - start)
                size = count * math.prod(image_shape) * np.dtype(np.float32).itemsize
                raw = renderer.stdout.read(size)
                if len(raw) != size:
                    raise ValueError(f"TEST image stream ended early at frame {start}")
                digest.update(raw)
                yield np.frombuffer(raw, dtype=np.float32).reshape(count, *image_shape).copy()
            if renderer.stdout.read(1) or renderer.wait():
                raise ValueError("TEST renderer failed or returned unexpected byte count")
        finally:
            if renderer.poll() is None:
                renderer.terminate()
    image_record.update({"frames": total_frames, "shape_chw": list(image_shape),
                         "dtype": "float32", "sha256_contiguous_chw_stream": digest.hexdigest()})


def make_forecast(out, cfg, lock, models, metrics, device, encoders, probes):
    development = lock["mode"] == "development_smoke"
    roles = {}
    for role in ("ref", "cal"):
        role_features = features_for_role(encoders, cfg, role, development, models, device)
        n, t = [cfg["roles"][role][key] for key in ("episodes", "frames")]
        roles[role] = {name: models.predict(probe, role_features[name], device).reshape(n, t, 4)
                       for name, probe in probes.items()}
    physical_ref = role_labels(cfg, "ref", development)
    physical_variance = physical_ref.reshape(-1, 4).var(0, ddof=0)
    save_npz(out / "reference_truth.npz", states=physical_ref, variance=physical_variance)
    thresholds = {}
    for name, probe in probes.items():
        folder = out / name
        ref = roles["ref"][name]
        ref_variance = ref.reshape(-1, 4).var(0, ddof=0)
        cal = roles["cal"][name]
        cal_scores = metrics.score_windows(cal, cal, ref_variance, ref_variance, cfg["lags"])
        # FourRoom uses NumPy's ordinary interpolated CAL quantile, on the scorer gap.
        threshold = float(np.quantile(cal_scores["gap"], cfg["cal_gap_quantile"], method="linear"))
        thresholds[name] = threshold
        save_npz(folder / "reference.npz", prediction=ref, variance=ref_variance)
        save_npz(folder / "calibration.npz", prediction=cal, scores=cal_scores["predicted_scores"],
                 gap=cal_scores["gap"])
        save_json(folder / "thresholds.json", {"own_cal": threshold})
    save_json(out / "thresholds.json", {"own_cal": thresholds, "quantile": cfg["cal_gap_quantile"],
                                       "method": "linear"})
    verify_locked_sources(lock)

    image_record = {}
    started_utc = utc_now()
    images = blind_image_batches(out, cfg, image_record)
    test_features = features_for_images(encoders, images, models, cfg, device)
    n, t = [cfg["roles"]["test"][key] for key in ("episodes", "frames")]
    for name, probe in probes.items():
        prediction = models.predict(probe, test_features[name], device).reshape(n, t, 4)
        save_npz(out / name / "test_prediction.npz", prediction=prediction)
    verify_locked_sources(lock)
    canonical_paths = ["thresholds.json", "reference_truth.npz"]
    canonical_paths += [f"{name}/{file}" for name in probes for file in (
        "thresholds.json", "test_prediction.npz", "reference.npz", "calibration.npz", "audit.json")]
    files = {path: sha256(out / path) for path in canonical_paths}
    receipt = {"evidence_tier": lock["evidence_tier"],
               "sealed_utc": utc_now(), "test_image_inference_started_utc": started_utc,
               "design_lock_sha256": sha256(out / "DESIGN_LOCK.json"),
               "test_image_stream": image_record, "files_sha256": files}
    save_json(out / "FORECAST_RECEIPT.json", receipt)
    print(f"Forecast sealed for {len(probes)} cells", flush=True)


def verify_forecast(out):
    receipt = read_json(out / "FORECAST_RECEIPT.json")
    lock = read_json(out / "DESIGN_LOCK.json")
    required = {"thresholds.json", "reference_truth.npz"}
    required.update(f"{name}/{file}" for name, _, _ in cells(lock["config"]) for file in (
        "thresholds.json", "test_prediction.npz", "reference.npz", "calibration.npz", "audit.json"))
    saved = receipt["files_sha256"]
    if set(saved) != required:
        raise ValueError("Forecast receipt does not cover exactly the locked cells and inputs")
    if receipt["design_lock_sha256"] != sha256(out / "DESIGN_LOCK.json"):
        raise ValueError("Design lock changed after forecast")
    mismatches = [path for path, digest in saved.items() if sha256(out / path) != digest]
    if mismatches:
        raise ValueError(f"Sealed forecast hashes failed: {mismatches}")
    if not lock["created_utc"] <= receipt["test_image_inference_started_utc"] <= receipt["sealed_utc"]:
        raise ValueError("Design/inference/forecast timestamps are inconsistent")
    return receipt, len(saved)


def subgroup(wrong, accept, mask):
    windows = int(mask.sum())
    selected = mask & accept
    n = int(selected.sum())
    errors = int(np.count_nonzero(wrong & mask))
    accepted_errors = int(np.count_nonzero(wrong & selected))
    return {"windows": windows,
            "all_answer": {"accepted": windows, "errors": errors,
                           "error_rate": errors / windows if windows else None},
            "own_cal": {"accepted": n, "errors": accepted_errors,
                        "error_rate": accepted_errors / n if n else None,
                        "coverage": n / windows if windows else None}}


def score_forecast(out, cfg, metrics, timing_start):
    receipt, checked = verify_forecast(out)
    truth_opened_utc = utc_now()
    if truth_opened_utc < receipt["sealed_utc"]:
        raise ValueError("Clock moved backwards before TEST scoring")
    fixture = cfg.get("fixture_only", False)
    truth = role_labels(fixture_panel(cfg), "audit", True) if fixture else role_labels(cfg, "test", False)
    save_npz(out / "test_truth.npz", states=truth)
    with np.load(out / "reference_truth.npz", allow_pickle=False) as data:
        physical_variance = data["variance"]
    thresholds = read_json(out / "thresholds.json")["own_cal"]
    rows = []
    alpha = cfg["family_alpha"] / len(cells(cfg))
    for name, arm, seed in cells(cfg):
        path = out / name
        with np.load(path / "test_prediction.npz", allow_pickle=False) as data:
            prediction = data["prediction"]
        with np.load(path / "reference.npz", allow_pickle=False) as data:
            predicted_variance = data["variance"]
        scores = metrics.score_windows(prediction, truth, physical_variance, predicted_variance, cfg["lags"])
        save_npz(path / "test_scores.npz", **scores)
        threshold = thresholds[name]
        selected = metrics.risk(scores["gap"], scores["wrong"], threshold, alpha,
                                cfg["minimum_coverage"], cfg["maximum_selective_error"])
        audit = read_json(path / "audit.json")
        passed = not fixture and audit["eligible"] and selected["passes"]
        regular = np.all(scores["true_top2"] == (0, 1), axis=1)
        accept = scores["gap"] >= threshold
        rows.append({"cell": name, "arm": arm, "seed": seed, "r2": audit["r2"],
                     "minimum_r2": audit["minimum_r2"], "eligible": audit["eligible"],
                     "threshold": threshold, "own_cal": selected, "passes": passed,
                     "status": "SMOKE_ONLY" if fixture else "RECOVERY_NOT_VERIFIED" if not audit["eligible"]
                     else "PASS" if passed else "FAIL",
                     "regular": subgroup(scores["wrong"], accept, regular),
                     "flip": subgroup(scores["wrong"], accept, ~regular)})

    verify_forecast(out)
    summary = {"evidence_tier": receipt["evidence_tier"],
               "status": "SMOKE_COMPLETE" if fixture else "COMPLETE", "axes": list(AXES),
               "rows": rows, "alpha": alpha, "family_size": len(rows),
               "test_truth_opened_utc": truth_opened_utc,
               "test_truth_sha256": sha256(out / "test_truth.npz"),
               "forecast_receipt_sha256": sha256(out / "FORECAST_RECEIPT.json"),
               "forecast_hashes_verified": checked,
               "elapsed_seconds": time.perf_counter() - timing_start,
               "finished_utc": utc_now()}
    save_json(out / "SUMMARY.json", summary)
    write_report(out, summary)


def write_report(out, summary):
    config = read_json(out / "DESIGN_LOCK.json")
    rows = summary["rows"]
    lines = ["# Two-Sprite visual comparison", "", f"Evidence tier: `{summary['evidence_tier']}`",
             f"Device: {config['device']}",
             f"Elapsed seconds: {summary['elapsed_seconds']:.1f}",
             f"Per-cell Bonferroni alpha: {summary['alpha']:.9f}",
             f"Forecast files verified: {summary['forecast_hashes_verified']}", "",
             "| Arm and seed | agent_x R² | agent_y R² | distractor_x R² | distractor_y R² | Eligible | Coverage | Errors / accepted | CP upper | Result |",
             "|---|---:|---:|---:|---:|---|---:|---:|---:|---|"]
    for row in rows:
        rates = row["own_cal"]
        axis_text = " | ".join(f"{row['r2'][axis]:.6f}" for axis in AXES)
        lines.append(f"| {row['cell']} | {axis_text} | {row['eligible']} | {rates['coverage']:.4%} | "
                     f"{rates['errors']}/{rates['accepted']} | {rates['error_upper']:.4%} | {row['status']} |")
    lines += ["", "| Arm and seed | Subset | All-answer errors / windows (risk) | own_cal errors / accepted (risk) |",
              "|---|---|---:|---:|"]
    for row in rows:
        for group in ("regular", "flip"):
            record = row[group]
            all_answer = record["all_answer"]
            own = record["own_cal"]
            all_risk = f"{all_answer['error_rate']:.4%}" if all_answer["error_rate"] is not None else "undefined"
            own_risk = f"{own['error_rate']:.4%}" if own["error_rate"] is not None else "undefined"
            lines.append(f"| {row['cell']} | {group} | {all_answer['errors']}/{record['windows']} ({all_risk}) | "
                         f"{own['errors']}/{own['accepted']} ({own_risk}) |")
    if config["mode"] == "development_smoke":
        lines += ["", "All figures here come from a tiny engineering fixture on disjoint development streams."]
    else:
        lines += ["", "Subgroup risks are descriptive. The six-cell family contains the prespecified overall own_cal claims. "
                  "All cells share the same TEST episodes. Local UTC timestamps and named hashes document the forecast-before-scoring order."]
    with (out / "RESULTS.md").open("x") as stream:
        stream.write("\n".join(lines) + "\n")


def smoke_config(cfg):
    """Diagnostic scale only. No formal TEST role is sampled by smoke."""
    config = deepcopy(cfg)
    config["fixture_only"] = True
    config["seeds"] = [cfg["development_model_seed"]]
    for role in config["roles"]:
        config["roles"][role]["episodes"] = min(config["roles"][role]["episodes"], 8)
    config["encoder"]["steps"] = 3
    config["encoder"]["batch_size"] = 16
    config["probe"]["steps"] = 3
    config["probe"]["batch_size"] = 16
    return config


def run(args):
    out = result_path(args.name)
    if args.render_test:
        render_test_stream(out)
        return
    if args.verify:
        receipt, checked = verify_forecast(out)
        summary = read_json(out / "SUMMARY.json")
        if summary["test_truth_opened_utc"] < receipt["sealed_utc"]:
            raise ValueError("Truth access was recorded before forecast sealing")
        if summary["test_truth_sha256"] != sha256(out / "test_truth.npz"):
            raise ValueError("Saved TEST truth differs from summary")
        if summary["forecast_receipt_sha256"] != sha256(out / "FORECAST_RECEIPT.json"):
            raise ValueError("Forecast receipt differs from summary")
        print(json.dumps({"status": "verified", "files_verified": checked,
                          "forecast_receipt_sha256": summary["forecast_receipt_sha256"]}))
        return

    timing_start = time.perf_counter()
    cfg = read_json(CONFIG)
    if "fixture_only" in cfg:
        raise ValueError("The fixture-only flag is reserved for engineering smoke")
    preflight = render.development_flip_check(cfg)
    if args.preflight:
        print(json.dumps(preflight, indent=2, allow_nan=False))
        return
    develop = args.development or args.smoke
    if not preflight["pass"] and not args.smoke:
        raise ValueError(f"Developer-only flip preflight did not meet the design: {preflight}")
    expected_prefix = "smoke_" if args.smoke else "development_" if args.development else "formal_"
    if not args.name.startswith(expected_prefix):
        raise ValueError(f"This run mode requires a directory name beginning {expected_prefix!r}")

    # Numerical dependencies and import of the vendor SIGReg are needed only for training.
    import torch
    import models

    if sys.prefix == sys.base_prefix:
        raise ValueError("Training must run in the isolated experiment virtual environment")
    device = models.configure_device(args.device, cfg["runtime"]["cpu_threads"])
    metrics = load_metrics()
    development_receipt = None
    if args.formal:
        development = result_path(args.development_name) / "DEVELOPMENT_RECEIPT.json"
        data = read_json(development)
        if (data["evidence_tier"] != "development" or not data["passes"]
                or data["source_sha256"] != source_hashes() or data["device"] != str(device)):
            raise ValueError("Formal run requires a passing development receipt for the exact code, config and device")
        development_receipt = {"path": str(development.relative_to(ROOT)), "sha256": sha256(development)}
    if args.smoke:
        cfg = smoke_config(cfg)
    mode = "development_smoke" if args.smoke else "development" if develop else "formal"
    lock = initialize_output(out, cfg, device, mode, preflight, development_receipt)
    try:
        encoders, probes, audit = prepare_models(out, cfg, models, torch, device, develop)
        if args.development:
            minimum = min(row["minimum_r2"] for row in audit.values())
            result = {"evidence_tier": mode, "source_sha256": lock["source_sha256"], "device": str(device),
                      "audit": audit, "minimum_r2": minimum,
                      "minimum_required_r2": cfg["development_min_r2"],
                      "passes": not args.smoke and minimum > cfg["development_min_r2"],
                      "elapsed_seconds": time.perf_counter() - timing_start, "finished_utc": utc_now()}
            save_json(out / "DEVELOPMENT_RECEIPT.json", result)
            print(json.dumps(result, indent=2), flush=True)
        else:
            make_forecast(out, cfg, lock, models, metrics, device, encoders, probes)
            score_forecast(out, cfg, metrics, timing_start)
            print(f"Complete: {out}", flush=True)
    except Exception as error:
        save_json(out / "FAILURE.json", {"error": repr(error), "failed_utc": utc_now()})
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--preflight", action="store_true", help="Run only the development flip diagnostic")
    group.add_argument("--development", action="store_true", help="Fit one development-only positive-arm model")
    group.add_argument("--smoke", action="store_true", help="Developer-only execution smoke, no formal TEST")
    group.add_argument("--formal", action="store_true", help="Run the six preregistered formal cells")
    group.add_argument("--verify", action="store_true", help="Verify a completed formal forecast and timestamps")
    group.add_argument("--render-test", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--name", help="Exclusive result directory name")
    parser.add_argument("--development-name", default="development_v1", help="Matching development receipt directory")
    parser.add_argument("--device", default="auto", choices=("auto", "cpu", "mps"))
    args = parser.parse_args()
    if args.name is None:
        args.name = "smoke_v1" if args.smoke else "development_v1" if args.development else "formal_v1"
    run(args)


if __name__ == "__main__":
    main()
